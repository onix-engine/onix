// Command ecsgen generates typed query, spawn and patch adapters around shared plans.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

func main() {
	output := flag.String("out", "query_iter.go", "generated Go file")
	patchOutput := flag.String("patches-out", "patch_typed.go", "generated typed patches")
	spawnOutput := flag.String("spawners-out", "spawner_typed.go", "generated typed spawners")
	flag.Parse()
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by internal/ecsgen; DO NOT EDIT.\n\npackage ecs")
	for count := 1; count <= 7; count++ {
		letters := strings.Split("A B C D E F G", " ")[:count]
		params := strings.Join(letters, ", ")
		result := "ComponentAccess[A]"
		name := "Query"
		if count > 1 {
			name += fmt.Sprint(count)
			result = fmt.Sprintf("Components%d[%s]", count, params)
			fmt.Fprintf(&source, "\n// Components%d contains explicitly tracked component access for one entity.\n", count)
			fmt.Fprintf(&source, "type Components%d[%s any] struct {\n", count, params)
			for _, letter := range letters {
				fmt.Fprintf(&source, "%s ComponentAccess[%s]\n", letter, letter)
			}
			fmt.Fprintln(&source, "}")
		}
		fmt.Fprintf(&source, "\n// %s iterates matching entities. Get and Ref do not mark changes; Mut does.\n", name)
		fmt.Fprintln(&source, "// Access values and component pointers must not outlive the iteration.")
		fmt.Fprintf(&source, "func %s[%s any](world *World, options ...QueryOption) QueryView%d[%s] {\nrequireWorld(world)\nids := [%d]componentID{", name, params, count, params, count)
		for _, letter := range letters {
			fmt.Fprintf(&source, "registerComponent[%s](world),", letter)
		}
		fmt.Fprintf(&source, "}\nkey := simpleQueryKey{count: %d}\ncopy(key.ids[:], ids[:])\nreturn QueryView%d[%s]{view: buildQuery(world, key, options), ids: ids}\n}\n", count, count, params)
		fmt.Fprintf(&source, "\n// QueryView%d retains a query plan and its filter snapshot. Range over All to iterate.\ntype QueryView%d[%s any] struct {\nview queryView\nids [%d]componentID\n}\n", count, count, params, count)
		fmt.Fprintln(&source, "\n// In limits traversal to the supplied entities, preserving their order.")
		fmt.Fprintln(&source, "// The list is borrowed and must not change during iteration. Nil visits none.")
		fmt.Fprintf(&source, "func (v QueryView%d[%s]) In(entities []Entity) QueryView%d[%s] {\nv.view.entities = entities\nv.view.limited = true\nreturn v\n}\n", count, params, count, params)
		fmt.Fprintf(&source, "\nfunc (v QueryView%d[%s]) All(yield func(Entity, %s) bool) {\ncursor, ok := v.view.cursor(yield != nil)\nif !ok { return }\ndefer cursor.close()\ntickBits := uint64(cursor.mutationTick()) << 32\n", count, params, result)
		fmt.Fprintln(&source, "if cursor.view.limited {\nvar current *archetype")
		for _, letter := range letters {
			fmt.Fprintf(&source, "var %s *typedColumn[%s]\n", strings.ToLower(letter), letter)
		}
		fmt.Fprintln(&source, "for cursor.nextEntity() {\nif cursor.archetype != current {\ncurrent = cursor.archetype")
		for index, letter := range letters {
			fmt.Fprintf(&source, "%s = componentColumn[%s](current, v.ids[%d])\n", strings.ToLower(letter), letter, index)
		}
		fmt.Fprintln(&source, "}\nrow := cursor.row\nentity := cursor.archetype.entities[row]")
		writeYield(&source, letters, count, params, false)
		fmt.Fprintln(&source, "}\nreturn\n}")
		fmt.Fprintln(&source, "for cursor.nextArchetype() {\nentities := cursor.archetype.entities")
		for index, letter := range letters {
			column := strings.ToLower(letter)
			fmt.Fprintf(&source, "%s := componentColumn[%s](cursor.archetype, v.ids[%d])\n%sValues := %s.values\n", column, letter, index, column, column)
		}
		// Keep the unfiltered scan free of filter bookkeeping.
		fmt.Fprintln(&source, "if v.view.filters.count == 0 {\nfor row := 0; row < len(entities); row++ {\nentity := entities[row]")
		writeYield(&source, letters, count, params, true)
		fmt.Fprintln(&source, "}\ncontinue\n}")
		source.WriteString("for row := 0; row < len(entities); row++ {\ncursor.row = row\nif row%queryTickBlockSize == 0 && !cursor.blockMatches() {\nrow = min(row+queryTickBlockSize, len(entities))-1\ncontinue\n}\nif !cursor.rowMatches() { continue }\nentity := entities[row]\n")
		writeYield(&source, letters, count, params, true)
		fmt.Fprintln(&source, "}\n}\n}")
	}
	writeSource(*output, source.Bytes())
	writeSpawners(*spawnOutput)
	writePatches(*patchOutput)
}

func writeSource(path string, source []byte) {
	formatted, err := format.Source(source)
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, formatted, 0644); err != nil {
		panic(err)
	}
}

func writeSpawners(path string) {
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by internal/ecsgen; DO NOT EDIT.\n\npackage ecs")
	for count := 1; count <= 8; count++ {
		letters := strings.Split("A B C D E F G H", " ")[:count]
		params := strings.Join(letters, ", ")
		name := fmt.Sprintf("Spawner%d", count)
		fmt.Fprintf(&source, "\n// %s binds component columns once for repeated allocation-free creation.\n", name)
		fmt.Fprintf(&source, "type %s[%s any] struct {\nplan spawnPlan\n", name, params)
		for _, letter := range letters {
			fmt.Fprintf(&source, "%s *typedColumn[%s]\n", strings.ToLower(letter), letter)
		}
		fmt.Fprintln(&source, "}")
		fmt.Fprintln(&source, "\n// Reserve preallocates the archetype and world metadata for capacity entities.")
		fmt.Fprintf(&source, "func (s *%s[%s]) Reserve(capacity int) {\nif s != nil { s.plan.reserve(capacity) }\n}\n", name, params)
		fmt.Fprintf(&source, "\nfunc New%s[%s any](world *World) %s[%s] {\n", name, params, name, params)
		for _, letter := range letters {
			fmt.Fprintf(&source, "%sID := registerComponent[%s](world)\n", strings.ToLower(letter), letter)
		}
		fmt.Fprintf(&source, "ids := [%d]componentID{", count)
		for _, letter := range letters {
			fmt.Fprintf(&source, "%sID,", strings.ToLower(letter))
		}
		fmt.Fprintf(&source, "}\nplan := newSpawnPlan(world, ids[:])\nreturn %s[%s]{plan: plan,\n", name, params)
		for _, letter := range letters {
			column := strings.ToLower(letter)
			fmt.Fprintf(&source, "%s: componentColumn[%s](plan.archetype, %sID),\n", column, letter, column)
		}
		fmt.Fprintln(&source, "}\n}")
		fmt.Fprintf(&source, "\nfunc (s *%s[%s]) Spawn(", name, params)
		for _, letter := range letters {
			fmt.Fprintf(&source, "%s %s,", strings.ToLower(letter), letter)
		}
		fmt.Fprintln(&source, ") Entity {\nentity, row, tick := s.plan.begin()")
		for _, letter := range letters {
			column := strings.ToLower(letter)
			fmt.Fprintf(&source, "s.%s.append(%s, tick)\n", column, column)
		}
		fmt.Fprintln(&source, "s.plan.finish(entity, row)\nreturn entity\n}")
	}
	writeSource(path, source.Bytes())
}

// writeYield keeps component access construction identical for both traversal paths.
func writeYield(source *bytes.Buffer, letters []string, count int, params string, localValues bool) {
	access := func(letter string) string {
		column := strings.ToLower(letter)
		values := column + ".values"
		if localValues {
			values = column + "Values"
		}
		return fmt.Sprintf("ComponentAccess[%s]{value: &%s[row], state: &%s.columnState, rowTick: tickBits | uint64(uint32(row))}", letter, values, column)
	}
	if count == 1 {
		fmt.Fprintf(source, "if !yield(entity, %s) { return }\n", access("A"))
		return
	}
	fmt.Fprintf(source, "if !yield(entity, Components%d[%s]{\n", count, params)
	for _, letter := range letters {
		fmt.Fprintf(source, "%s: %s,\n", letter, access(letter))
	}
	fmt.Fprintln(source, "}) { return }")
}

func writePatches(path string) {
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by internal/ecsgen; DO NOT EDIT.\n\npackage ecs")
	for count := 1; count <= 8; count++ {
		letters := strings.Split("A B C D E F G H", " ")[:count]
		params := strings.Join(letters, ", ")
		name := fmt.Sprintf("Patch%d", count)
		var arguments, values []string
		for _, letter := range letters {
			values = append(values, strings.ToLower(letter))
			arguments = append(arguments, strings.ToLower(letter)+" "+letter)
		}
		args := strings.Join(arguments, ", ")
		vals := strings.Join(values, ", ")
		fmt.Fprintf(&source, "\n// %s upserts typed values and removes other components in one migration.\n", name)
		fmt.Fprintln(&source, "// Prepare once per world; copies share transitions. Inserted types take precedence over removals.")
		fmt.Fprintf(&source, "type %s[%s any] struct { plan *patchPlan }\n", name, params)
		fmt.Fprintf(&source, "func New%s[%s any](world *World, removed ...ComponentType) %s[%s] {\nrequireWorld(world)\nworld.assertStructuralMutationAllowed()\nids := [%d]componentID{", name, params, name, params, count)
		for _, letter := range letters {
			fmt.Fprintf(&source, "registerComponent[%s](world),", letter)
		}
		fmt.Fprintf(&source, "}\nreturn %s[%s]{plan: newPatchPlan(world, ids[:], removed)}\n}\n", name, params)
		fmt.Fprintf(&source, "\n// Reserve prepares existing source transitions and destination capacities.\nfunc (p %s[%s]) Reserve(capacity int) { p.plan.reserve(capacity) }\n", name, params)
		fmt.Fprintln(&source, "\n// Apply preserves Added for replacements and both ticks for retained values.")
		fmt.Fprintln(&source, "// Cleanup hooks run before any writes; warmed transitions and capacities allocate nothing.")
		fmt.Fprintf(&source, "func (p %s[%s]) Apply(entity Entity, %s) error {\nrow, err := p.plan.begin(entity)\nif err != nil { return err }\n", name, params, args)
		for index, value := range values {
			fmt.Fprintf(&source, "writePatchColumn(row, %d, %s)\n", index, value)
		}
		fmt.Fprintln(&source, "p.plan.finish(row)\nreturn nil\n}")
		fmt.Fprintln(&source, "\n// Queue copies typed values into reusable command storage for deferred application.")
		fmt.Fprintf(&source, "func (p %s[%s]) Queue(commands *Commands, entity Entity, %s) {\nqueuePatch(commands, entity, p.plan, patchCommand%d[%s]{patch: p, ", name, params, args, count, params)
		for _, value := range values {
			fmt.Fprintf(&source, "%s: %s,", value, value)
		}
		fmt.Fprintln(&source, "})\n}")
		fmt.Fprintf(&source, "type patchCommand%d[%s any] struct {\npatch %s[%s]\n", count, params, name, params)
		for _, argument := range arguments {
			fmt.Fprintln(&source, argument)
		}
		fmt.Fprintln(&source, "}")
		fmt.Fprintf(&source, "func (v patchCommand%d[%s]) apply(_ *World, entity Entity) error { return v.patch.Apply(entity, %s) }\n", count, params, "v."+strings.Join(values, ", v."))
		if count > 1 {
			fmt.Fprintf(&source, "type patchCache%d[%s any] struct{}\n", count, params)
			fmt.Fprintln(&source, "\n// Insert"+fmt.Sprint(count)+" upserts values together, reusing a world-local patch plan.")
			fmt.Fprintf(&source, "func Insert%d[%s any](world *World, entity Entity, %s) error {\np := FrameValue[patchCache%d[%s], %s[%s]](world)\nif p.plan == nil { *p = New%s[%s](world) }\nreturn p.Apply(entity, %s)\n}\n", count, params, args, count, params, name, params, name, params, vals)
		}
	}
	writeSource(path, source.Bytes())
}
