"""Regenerate Charlie Smith masking and directional albedo (requires numpy).

Gauss-Legendre integration over NdotH/NdotL and midpoint azimuth integration.
Smith projected area is integral(max(VdotH,0)*D(H), dH), G1=NdotV/area.
Integrating the resulting correlated visibility gives the same BRDF's albedo.
Both constants share one lookup; no texture or uniform space is required.
"""
import pathlib
import re
from functools import cache
import numpy as np


@cache
def quadrature(resolution):
    points, weights = np.polynomial.legendre.leggauss(resolution)
    phi = (np.arange(resolution * 4) + 0.5) * (2.0 * np.pi / (resolution * 4))
    return (points[:, None] + 1.0) * 0.5, weights * np.pi, np.cos(phi)


def distribution(nh2, roughness):
    inverse = 1.0 / roughness ** 2
    return (2.0 + inverse) * np.maximum(1.0 - nh2, 0.0) ** (0.5 * inverse) / (2.0 * np.pi)


def smith(nv, roughness, resolution=128):
    nh, weights, cosine = quadrature(resolution)
    vh = nv * nh + np.sqrt(1.0 - nv * nv) * np.sqrt(1.0 - nh * nh) * cosine
    area = np.sum(np.mean(np.maximum(vh, 0.0) * distribution(nh * nh, roughness), axis=1) * weights)
    return float(min(1.0, nv / max(area, 1e-16)))


def integrate(nv, roughness, resolution=128):
    nl, weights, cosine = quadrature(resolution)
    gv = smith(nv, roughness, resolution)
    gl = np.array([smith(float(l), roughness, resolution) for l in nl[:, 0]])[:, None]
    vh2 = 2.0 + 2.0 * (nv * nl + np.sqrt(1.0 - nv * nv) * np.sqrt(1.0 - nl * nl) * cosine)
    nh2 = (nv + nl) ** 2 / np.maximum(vh2, 1e-16)
    visibility_nl = gv * gl / (gv + gl - gv * gl) / (4.0 * nv)
    return float(np.sum(np.mean(distribution(nh2, roughness) * visibility_nl, axis=1) * weights)), gv


if __name__ == '__main__':
    # Light-direction masking does not depend on view: compute it once per row.
    nl, weights, cosine = quadrature(128)
    table = np.zeros((16, 32, 2))
    for y in range(16):
        roughness = 0.045 + 0.955 * (y / 15.0) ** 2
        gl = np.array([smith(float(l), roughness) for l in nl[:, 0]])[:, None]
        for x in range(32):
            nv = max((x / 31.0) ** 3, 1e-7)
            gv = smith(nv, roughness)
            vh2 = 2.0 + 2.0 * (nv * nl + np.sqrt(1.0 - nv * nv) * np.sqrt(1.0 - nl * nl) * cosine)
            nh2 = (nv + nl) ** 2 / np.maximum(vh2, 1e-16)
            visibility_nl = gv * gl / (gv + gl - gv * gl) / (4.0 * nv)
            albedo = float(np.sum(np.mean(distribution(nh2, roughness) * visibility_nl, axis=1) * weights))
            table[y, x] = (gv / nv, albedo)
    assert np.all(table >= 0.0) and np.all(table[:,:,1] <= 1.00001), table.max()
    table[:,:,1] = np.minimum(table[:,:,1], 1.0)
    error = 0.0
    for nv in (0.0001, 0.01, 0.12, 0.35, 0.7, 1.0):
        for roughness in (0.045, 0.3, 0.8, 1.0):
            x, y = nv ** (1.0 / 3.0) * 31.0, np.sqrt((roughness - 0.045) / 0.955) * 15.0
            ix, iy = min(int(x), 30), min(int(y), 14)
            fx, fy = x - ix, y - iy
            approximation = ((table[iy, ix] * (1 - fx) + table[iy, ix + 1] * fx) * (1 - fy)
                             + (table[iy + 1, ix] * (1 - fx) + table[iy + 1, ix + 1] * fx) * fy)
            albedo, gv = integrate(nv, roughness, 192)
            error = max(error, float(np.max(np.abs(approximation * (nv, 1.0) - (gv, albedo)))))
    assert error < 0.025, error
    lines = [', '.join(f'vec2<f32>({v[0]:.8f},{v[1]:.8f})' for v in row) + ',' for row in table]
    block = ('// BEGIN_SHEEN_ALBEDO\n// Generated by internal/shadergen/sheen_albedo.py: G1/NdotV, directional albedo.\n'
             'const SHEEN_ALBEDO: array<vec2<f32>,512> = array<vec2<f32>,512>(\n    '
             + '\n    '.join(lines) + '\n);\n// END_SHEEN_ALBEDO')
    path = pathlib.Path(__file__).resolve().parents[2] / 'shaders/mesh.frag.wgsl'
    source = re.sub(r'// SHEEN_ALBEDO_TABLE|// BEGIN_SHEEN_ALBEDO.*?// END_SHEEN_ALBEDO', block, path.read_text(), flags=re.S)
    path.write_text(source)
    print(f'Charlie Smith response: maximum checked interpolation error {error:.6f}')
