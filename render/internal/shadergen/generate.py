"""Generate the four built-in fragments from WGSL (naga + a SPIR-V compiler)."""
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
from variants import specialize

root = pathlib.Path(__file__).resolve().parents[2]
shaders = root / 'shaders'
textures = [
    (1, 'tex'), (3, 'normalTex'), (6, 'metallicRoughnessTex'),
    (8, 'occlusionTex'), (10, 'emissiveTex'), (12, 'specularTex'),
    (14, 'specularColorTex'), (16, 'environmentTex'), (18, 'shadowTex'),
    (20, 'screenDepthTex'), (22, 'clearcoatTex'), (24, 'clearcoatRoughnessTex'),
    (26, 'clearcoatNormalTex'), (28, 'sheenColorTex'),
    (30, 'sheenRoughnessTex'), (32, 'anisotropyTex'),
]
samplers = ['texSampler'] + [name.removesuffix('Tex') + 'Sampler' for _, name in textures[1:]]
compiler = shutil.which('glslangValidator') or shutil.which('glslc')
if not compiler:
    raise RuntimeError('Install glslangValidator or glslc to generate SPIR-V')
compiler_flags = ['-V'] if pathlib.Path(compiler).stem == 'glslangValidator' else []


def compile_spirv(path):
    subprocess.run([compiler, *compiler_flags, str(path), '-o', str(path) + '.spv'], check=True)


def generate_native(source_path, output_suffix, directory, compact):
    glsl_path, metal_path = directory / 'fragment.frag', directory / 'fragment.metal'
    subprocess.run([
        'naga', str(source_path), str(glsl_path), str(metal_path),
        '--entry-point', 'mesh_fragment', '--profile', 'es300',
        '--keep-coordinate-space', *(['--compact'] if compact else []),
    ], check=True)
    source = glsl_path.read_text()
    uniform = re.search(r'^.*uniform PBRUniforms_block_0Fragment \{.*\};$', source, re.M).group(0)
    fields = re.search(r'struct PBRUniforms \{(.*?)\n\};', source, re.S).group(1).strip().splitlines()
    gles = source.replace(uniform, '\n'.join('uniform ' + line.strip() for line in fields))
    gles = gles.replace('_group_0_binding_0_fs.', '').replace('const bool SHADOW_FLIP_Y = true;', 'const bool SHADOW_FLIP_Y = false;')
    vk = source.replace('#version 300 es', '#version 450').replace('precision highp float;', '').replace('precision highp int;', '')
    vk = vk.replace(uniform, 'layout(set=2,binding=1,std140) uniform PBRUniforms_block_0Fragment { PBRUniforms _group_0_binding_0_fs; };')
    metal = metal_path.read_text().replace('pbr [[user(fake0)]]', 'pbr [[buffer(2)]]')
    for index, ((binding, name), sampler) in enumerate(zip(textures, samplers)):
        descriptor = (0, 0) if index == 0 else (1, 0) if index == 1 else (3, index - 2)
        original = f'uniform highp sampler2D _group_0_binding_{binding}_fs;'
        vk = vk.replace(original, f'layout(set={descriptor[0]},binding={descriptor[1]}) uniform sampler2D {name};')
        vk = vk.replace(f'_group_0_binding_{binding}_fs', name)
        gles = gles.replace(f'_group_0_binding_{binding}_fs', name)
        metal = metal.replace(name + ' [[user(fake0)]]', name + f' [[texture({index})]]')
        metal = metal.replace(sampler + ' [[user(fake0)]]', sampler + f' [[sampler({index})]]')
    if 'fake0' in metal:
        raise RuntimeError('unmapped Metal binding')
    vk = re.sub(r'(smooth|flat) in (\w+) _vs2fs_location(\d+);', lambda m: f'layout(location={m[3]}) {m[1]} in {m[2]} _vs2fs_location{m[3]};', vk)
    label = f'{output_suffix[1:]} variant from mesh.frag.wgsl.' if output_suffix else 'from mesh.frag.wgsl.'
    for backend, version, text in [('gles', '300 es', gles), ('vulkan', '450', vk)]:
        path = shaders / f'{backend}_mesh{output_suffix}.frag'
        path.write_text(text.replace(f'#version {version}', f'#version {version}\n// Generated {label}', 1).rstrip() + '\n')
        if backend == 'vulkan':
            compile_spirv(path)
    (shaders / f'metal_mesh{output_suffix}_fragment.inc').write_text('// Generated from mesh.frag.wgsl.\n' + '\n'.join(json.dumps(line + '\n') for line in metal.splitlines()) + '\n')


with tempfile.TemporaryDirectory(prefix='onix-shader-') as temporary:
    directory = pathlib.Path(temporary)
    shared = shaders / 'mesh.frag.wgsl'
    generate_native(shared, '', directory, False)
    compile_spirv(shaders / 'vulkan_mesh.vert')
    # A fixed set avoids the cross product of all material feature flags.
    for kind in ['unlit', 'depth', 'basic']:
        path = shaders / f'mesh_{kind}.frag.wgsl'
        path.write_text('// Generated by internal/shadergen.\n' + specialize(shared.read_text(), kind))
        generate_native(path, '_' + kind, directory, True)
