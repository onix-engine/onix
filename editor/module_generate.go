const moduleGeneratedHeader = "// Code generated by Onix; DO NOT EDIT.\n"
const moduleAPI = "github.com/diiyw/onix/module"

type moduleGoPackage struct {
	name, importPath string
	types            map[string]bool
	methods          map[string]map[string]moduleGoMethod
}
type moduleGoMethod struct {
	signature, file string
	pointer         bool
}
type moduleBehavior struct {
	id, file, typeName, alias string
	scene                     bool
	used                      bool
	pkg                       *moduleGoPackage
}

// GenerateModuleProject validates source boundaries and signatures before
// replacing generated files. The user's entry and behavior sources are read only.
func GenerateModuleProject(directory string) (*project.ProjectPlan, error) {
	return generateModuleProject(directory, true)
}

// CheckModuleProject performs the same checks without changing generated files.
func CheckModuleProject(directory string) (*project.ProjectPlan, error) {
	return generateModuleProject(directory, false)
}

func generateModuleProject(directory string, write bool) (*project.ProjectPlan, error) {
	directory, err := filepath.Abs(directory)
	if err != nil {
		return nil, err
	}
	plan, err := project.CompileProjectDirectory(directory)
	if err != nil {
		return nil, err
	}
	root, err := findRepoRoot(directory)
	if err != nil {
		return nil, err
	}
	_, importPath, err := resolveGoPackagePath(root, directory)
	if err != nil {
		return nil, err
	}
	packages, err := inspectModuleGoSources(directory, importPath, plan)
	if err != nil {
		return nil, err
	}
	mainPackage := packages["."]
	if mainPackage == nil {
		return nil, fmt.Errorf("%s: main.go is required", directory)
	}
	contractsPath := importPath + "/contracts"
	typesSource, err := generateModuleContracts(plan.Spec.Types)
	if err != nil {
		return nil, err
	}
	if pkg := packages["contracts"]; pkg != nil {
		for name := range plan.Spec.Types {
			if pkg.types[string(name)] {
				return nil, fmt.Errorf("contracts: type %s is reserved for project.types generation", name)
			}
		}
	}
	var behaviors []moduleBehavior
	used := make(map[project.ModID]bool)
	for _, s := range plan.Scenes {
		for _, i := range s.Instances {
			used[plan.Mods[i.Mod].ID] = true
		}
	}
	for _, mod := range plan.Mods {
		if mod.Spec.Behavior != "" {
			behaviors = append(behaviors, moduleBehavior{id: string(mod.ID), file: path.Join(string(mod.ID), "mod.json"), typeName: mod.Spec.Behavior, used: used[mod.ID], pkg: packages[string(mod.ID)]})
		}
	}
	for _, scene := range plan.Scenes {
		if scene.Spec.Behavior != "" {
			behaviors = append(behaviors, moduleBehavior{id: string(scene.ID), file: project.ScenePath(scene.ID), typeName: scene.Spec.Behavior, scene: true, used: true, pkg: mainPackage})
		}
	}
	slices.SortFunc(behaviors, func(a, b moduleBehavior) int { return strings.Compare(a.file, b.file) })
	imports := map[string]string{"onix": "github.com/diiyw/onix", "module": moduleAPI}
	if len(plan.Spec.Types) != 0 {
		imports["contracts"] = contractsPath
	}
	for i := range behaviors {
		b := &behaviors[i]
		if b.pkg == nil || !b.pkg.types[b.typeName] {
			return nil, fmt.Errorf("%s: behavior %s must be a declared Go struct", b.file, b.typeName)
		}
		if !b.scene {
			if b.pkg.name == "main" {
				return nil, fmt.Errorf("%s: module code must be an importable package", b.file)
			}
			b.alias = fmt.Sprintf("mod%d", i)
			if b.used {
				imports[b.alias] = b.pkg.importPath
			}
		}
		if err := checkModuleBehavior(*b); err != nil {
			return nil, err
		}
	}
	config, err := loadResourcePackageConfig(directory)
	if err != nil {
		return nil, err
	}
	if err := validateResourcePackageConfig(config); err != nil {
		return nil, err
	}
	assets, err := collectModuleAssets(directory, plan, config)
	if err != nil {
		return nil, err
	}
	var body strings.Builder
	body.WriteString("func OnixRegistry() (module.Registry, error) {\nr := module.Registry{}\n")
	for _, name := range sortedWorkspaceKeys(plan.Spec.Types) {
		fmt.Fprintf(&body, "if err := r.RegisterValue(%q, contracts.Decode%s); err != nil { return r, err }\n", name, name)
	}
	for _, b := range behaviors {
		if !b.used {
			continue
		}
		typeName := b.typeName
		if b.alias != "" {
			typeName = b.alias + "." + typeName
		}
		register := "RegisterMod"
		if b.scene {
			register = "RegisterScene"
		}
		fmt.Fprintf(&body, "if err := r.%s(%q, func() %s { return %s{} }, module.Lifecycle[%s]{\n", register, b.id, typeName, typeName, typeName)
		fmt.Fprintf(&body, "Install: func(c *module.Context, m *%s) error {\n", typeName)
		if _, ok := b.pkg.methods[b.typeName]["Install"]; ok {
			body.WriteString("return m.Install(c)\n")
		} else {
			body.WriteString("return nil\n")
		}
		body.WriteString("},\n")
		for _, hook := range []string{"Enter", "Exit", "Suspend", "Resume", "Update", "FrameUpdate", "OnMessage", "Destroy"} {
			if _, ok := b.pkg.methods[b.typeName][hook]; ok {
				extra, argument := "", ""
				if hook == "Enter" || hook == "Resume" {
					extra, argument = ", startup module.SceneStartup", ", startup"
				}
				if hook == "Update" || hook == "FrameUpdate" {
					extra = ", tick module.Tick"
					argument = ", tick"
				}
				if hook == "OnMessage" {
					extra = ", message module.Message"
					argument = ", message"
				}
				fmt.Fprintf(&body, "%s: func(c *module.Context, m *%s%s) error { return m.%s(c%s) },\n", hook, typeName, extra, hook, argument)
			}
		}
		body.WriteString("}); err != nil { return r, err }\n")
	}
	body.WriteString("return r, nil\n}\n\nfunc OnixInstallSystems(app *onix.App) error {\n")
	features := plan.RuntimeFeatures()
	contentProfile := "module.Render2D"
	contentCapabilities := make(map[string]bool)
	for _, f := range projectRuntimeFeatureDescriptors {
		if !slices.Contains(features, f.ID) {
			continue
		}
		for _, capability := range f.Content {
			if !contentCapabilities[capability] {
				contentProfile = fmt.Sprintf("module.WithContent[%s, module.%s]", contentProfile, capability)
				contentCapabilities[capability] = true
			}
		}
		if f.ImportPath != "" {
			imports[f.ImportName] = f.ImportPath
		}
		if f.Register {
			fmt.Fprintf(&body, "%s.Register()\n", f.ImportName)
		}
		if f.GoType != "" {
			fmt.Fprintf(&body, "if err := app.InstallSystems[onix.%s](); err != nil { return err }\n", f.GoType)
		}
	}
	body.WriteString("return nil\n}\n")
	fmt.Fprintf(&body, "\ntype OnixContentProfile = %s\n", contentProfile)
	// Decoder types are selected at generation time. Unused formats do not enter
	// the game's import graph; private content installers can use this decoder.
	decoderIDs := slices.Clone(plan.Spec.Engine.ImageDecoders)
	svgUsed := false
	for name := range assets {
		var id project.ImageDecoderID
		switch strings.ToLower(path.Ext(name)) {
		case ".png":
			id = project.ImageDecoderPNG
		case ".jpg", ".jpeg":
			id = project.ImageDecoderJPEG
		case ".gif":
			id = project.ImageDecoderGIF
		case ".webp":
			id = project.ImageDecoderWebP
		case ".svg":
			svgUsed = true
		}
		if id != "" && !slices.Contains(decoderIDs, id) {
			decoderIDs = append(decoderIDs, id)
		}
	}
	{
		imports["graphics"] = "github.com/diiyw/onix/graphics"
		decoderTypes := make([]string, 0, 5)
		for _, d := range projectImageDecoderDescriptors {
			t := "graphics.NoImageDecoder"
			if slices.Contains(decoderIDs, d.ID) {
				imports[d.ImportName] = d.ImportPath
				t = d.GoType
			}
			decoderTypes = append(decoderTypes, t)
		}
		t := "graphics.NoImageDecoder"
		if plan.Spec.Engine.TextureCompression {
			imports[projectTextureContainerDecoder.ImportName] = projectTextureContainerDecoder.ImportPath
			t = projectTextureContainerDecoder.GoType
		}
		decoderTypes = append(decoderTypes, t)
		if svgUsed {
			imports["graphicssvg"] = "github.com/diiyw/onix/graphics/codec/svg"
			fmt.Fprintf(&body, "\ntype OnixRasterImageDecoder = graphics.ImageDecoderSet[%s]\ntype OnixImageDecoder = graphics.ImageDecoderWith[OnixRasterImageDecoder,graphicssvg.Decoder]\n", strings.Join(decoderTypes, ","))
		} else {
			fmt.Fprintf(&body, "\ntype OnixImageDecoder = graphics.ImageDecoderSet[%s]\n", strings.Join(decoderTypes, ","))
		}
	}
	imports["project"] = "github.com/diiyw/onix/project"
	imports["iofs"] = "io/fs"
	resourceType := "project.ImageFeature[OnixImageDecoder]"
	audioTypes := []string{"audio.NoDecoder", "audio.NoDecoder", "audio.NoDecoder", "audio.NoDecoder"}
	audioUsed := false
	for _, mod := range plan.Mods {
		for _, resource := range mod.Resources {
			if resource.Kind != "audio" {
				continue
			}
			if _, used := assets[resource.Path]; !used {
				continue
			}
			name := resource.Path
			index, alias := -1, ""
			switch strings.ToLower(path.Ext(name)) {
			case ".wav":
				index, alias = 0, "wav"
			case ".mp3":
				index, alias = 1, "mp3"
			case ".ogg":
				index, alias = 2, "vorbis"
			case ".flac":
				index, alias = 3, "flac"
			}
			if index >= 0 {
				audioUsed = true
				imports["audio"+alias] = "github.com/diiyw/onix/audio/codec/" + alias
				audioTypes[index] = "audio" + alias + ".Decoder"
			}
		}
	}
	if audioUsed {
		imports["audio"] = "github.com/diiyw/onix/audio"
		imports["projectaudio"] = "github.com/diiyw/onix/project/audio"
		resourceType = "project.ResourceFeatureSet[" + resourceType + ", projectaudio.Feature[audio.DecoderSet[" + strings.Join(audioTypes, ",") + "]]]"
	}
	fmt.Fprintf(&body, "\nfunc OnixModuleOptions(source iofs.FS) module.Options { return module.Options{Source: source, Resources: %s{}} }\n", resourceType)
	iconDecoder := "nil"
	if plan.Spec.Window.Icon != "" {
		switch strings.ToLower(path.Ext(plan.Spec.Window.Icon)) {
		case ".png":
			imports["windowpng"] = "github.com/diiyw/onix/window/codec/png"
			iconDecoder = "windowpng.Decoder{}"
		case ".svg":
			imports["windowsvg"] = "github.com/diiyw/onix/window/codec/svg"
			iconDecoder = "windowsvg.Decoder[windowsvg.Size128]{}"
		default:
			return nil, fmt.Errorf("window icon must use PNG or SVG")
		}
	}
	fmt.Fprintf(&body, "\nfunc OnixOpenWindow(app *onix.App,spec project.ProjectSpec,source iofs.FS) error {return app.OpenModuleWindow(spec,source,%s)}\n", iconDecoder)
	var source strings.Builder
	source.WriteString(moduleGeneratedHeader + "package " + mainPackage.name + "\n\nimport (\n")
	for _, alias := range sortedWorkspaceKeys(imports) {
		fmt.Fprintf(&source, "%s %q\n", alias, imports[alias])
	}
	source.WriteString(")\n\n" + body.String())
	data, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format module registry: %w", err)
	}
	generated := map[string][]byte{"onix_generated.go": data}
	if len(plan.Spec.Types) > 0 {
		generated["contracts/onix_generated.go"] = typesSource
	}
	// Preflight all generated targets, including a stale contract file, before writing.
	for _, file := range []string{"onix_generated.go", "contracts/onix_generated.go"} {
		previous, err := os.ReadFile(filepath.Join(directory, filepath.FromSlash(file)))
		if err == nil && !bytes.HasPrefix(previous, []byte(moduleGeneratedHeader)) {
			return nil, fmt.Errorf("%s is reserved for generated code; user file was preserved", file)
		}
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
	}
	if !write {
		return plan, nil
	}
	for _, file := range sortedWorkspaceKeys(generated) {
		name := filepath.Join(directory, filepath.FromSlash(file))
		if err := os.MkdirAll(filepath.Dir(name), 0o755); err != nil {
			return nil, err
		}
		if previous, _ := os.ReadFile(name); bytes.Equal(previous, generated[file]) {
			continue
		}
		if err := writeAtomic(name, generated[file]); err != nil {
			return nil, err
		}
	}
	if len(plan.Spec.Types) == 0 {
		if err := os.Remove(filepath.Join(directory, "contracts", "onix_generated.go")); err != nil && !os.IsNotExist(err) {
			return nil, err
		}
	}
	return plan, nil
}

func inspectModuleGoSources(directory, importPath string, plan *project.ProjectPlan) (map[string]*moduleGoPackage, error) {
	packages := make(map[string]*moduleGoPackage)
	owners := newModuleOwnerIndex(plan)
	owner := owners.owner
	err := filepath.WalkDir(directory, func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		rel, err := filepath.Rel(directory, name)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if entry.IsDir() {
			if entry.Name() == "dist" || strings.HasPrefix(entry.Name(), ".") {
				if rel != "." {
					return filepath.SkipDir
				}
			}
			return nil
		}
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || rel == "onix_generated.go" || rel == "contracts/onix_generated.go" {
			return nil
		}
		matches, err := build.Default.MatchFile(filepath.Dir(name), filepath.Base(name))
		if err != nil {
			return fmt.Errorf("%s: %w", rel, err)
		}
		if !matches {
			return nil
		}
		file, err := parser.ParseFile(token.NewFileSet(), name, nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("%s: %w", rel, err)
		}
		pkgDir := path.Dir(rel)
		pkg := packages[pkgDir]
		if pkg == nil {
			pkg = &moduleGoPackage{name: file.Name.Name, importPath: importPath, types: make(map[string]bool), methods: make(map[string]map[string]moduleGoMethod)}
			if pkgDir != "." {
				pkg.importPath += "/" + pkgDir
			}
			packages[pkgDir] = pkg
		}
		if pkg.name != file.Name.Name {
			return fmt.Errorf("%s: mixed Go packages %s and %s", rel, pkg.name, file.Name.Name)
		}
		aliases := make(map[string]string)
		from := owner(pkgDir)
		real, err := filepath.EvalSymlinks(name)
		if err != nil {
			return err
		}
		realProject, err := filepath.EvalSymlinks(directory)
		if err != nil {
			return err
		}
		physical, err := filepath.Rel(realProject, real)
		if err != nil || !filepath.IsLocal(physical) || owner(filepath.ToSlash(physical)) != from {
			return fmt.Errorf("%s: Go source symlink crosses module boundary", rel)
		}
		for _, group := range file.Comments {
			for _, comment := range group.List {
				if !strings.HasPrefix(comment.Text, "//go:embed ") {
					continue
				}
				patterns, err := moduleEmbedPatterns(strings.TrimPrefix(comment.Text, "//go:embed "))
				if err != nil {
					return fmt.Errorf("%s: %w", rel, err)
				}
				for _, pattern := range patterns {
					pattern = strings.TrimPrefix(pattern, "all:")
					if !fs.ValidPath(pattern) || strings.ContainsAny(pattern, `\:`) {
						return fmt.Errorf("%s: embed pattern %q must stay within its module", rel, pattern)
					}
					matches, err := filepath.Glob(filepath.Join(filepath.Dir(name), filepath.FromSlash(pattern)))
					if err != nil {
						return err
					}
					for _, match := range matches {
						err := filepath.WalkDir(match, func(asset string, e fs.DirEntry, walkErr error) error {
							if walkErr != nil {
								return walkErr
							}
							relative, err := filepath.Rel(directory, asset)
							if err != nil {
								return err
							}
							if to := owner(filepath.ToSlash(relative)); to != from {
								return fmt.Errorf("%s: embed %q crosses module boundary %q", rel, pattern, to)
							}
							return nil
						})
						if err != nil {
							return err
						}
					}
				}
			}
		}
		for _, spec := range file.Imports {
			p, err := strconv.Unquote(spec.Path.Value)
			if err != nil {
				return err
			}
			alias := path.Base(p)
			if spec.Name != nil {
				alias = spec.Name.Name
			}
			if alias == "." {
				return fmt.Errorf("%s: dot imports prevent explicit protocol checking", rel)
			}
			aliases[alias] = p
			if p == importPath || strings.HasPrefix(p, importPath+"/") {
				target := strings.TrimPrefix(strings.TrimPrefix(p, importPath), "/")
				to := owner(target)
				if to != "" && to != from {
					return fmt.Errorf("%s: import %q depends on module %q; use events and data-only contracts", rel, p, to)
				}
			}
		}
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				if d.Tok == token.TYPE {
					for _, s := range d.Specs {
						t := s.(*ast.TypeSpec)
						_, ok := t.Type.(*ast.StructType)
						if ok && t.TypeParams == nil {
							pkg.types[t.Name.Name] = true
						}
					}
				}
			case *ast.FuncDecl:
				if d.Recv == nil {
					if pkgDir == "." && (d.Name.Name == "OnixRegistry" || d.Name.Name == "OnixInstallSystems" || d.Name.Name == "OnixModuleOptions" || d.Name.Name == "OnixOpenWindow") {
						return fmt.Errorf("%s: %s is reserved for generated code", rel, d.Name.Name)
					}
					continue
				}
				receiver := d.Recv.List[0].Type
				star, pointer := receiver.(*ast.StarExpr)
				if pointer {
					receiver = star.X
				}
				id, ok := receiver.(*ast.Ident)
				if !ok {
					continue
				}
				if pkg.methods[id.Name] == nil {
					pkg.methods[id.Name] = make(map[string]moduleGoMethod)
				}
				if _, ok := pkg.methods[id.Name][d.Name.Name]; ok {
					return fmt.Errorf("%s: duplicate method %s.%s", rel, id.Name, d.Name.Name)
				}
				pkg.methods[id.Name][d.Name.Name] = moduleGoMethod{file: rel, pointer: pointer, signature: canonicalModuleFields(d.Type.Params, aliases, pkg.importPath) + " -> " + canonicalModuleFields(d.Type.Results, aliases, pkg.importPath)}
			}
		}
		if pkgDir == "contracts" {
			for _, decl := range file.Decls {
				if _, ok := decl.(*ast.FuncDecl); ok {
					return fmt.Errorf("%s: contracts must contain data declarations only", rel)
				}
				if d, ok := decl.(*ast.GenDecl); ok && d.Tok == token.VAR {
					return fmt.Errorf("%s: contracts must contain data declarations only", rel)
				}
			}
		}
		return nil
	})
	return packages, err
}

func moduleEmbedPatterns(value string) ([]string, error) {
	var result []string
	for value = strings.TrimSpace(value); value != ""; value = strings.TrimSpace(value) {
		if value[0] == '"' || value[0] == '`' {
			quote := value[0]
			end := 1
			for end < len(value) {
				if value[end] == quote {
					break
				}
				if value[end] == '\\' && quote == '"' {
					end++
				}
				end++
			}
			if end >= len(value) {
				return nil, fmt.Errorf("unterminated embed pattern")
			}
			pattern, err := strconv.Unquote(value[:end+1])
			if err != nil {
				return nil, err
			}
			result = append(result, pattern)
			value = value[end+1:]
		} else {
			end := strings.IndexAny(value, " \t\r\n")
			if end < 0 {
				end = len(value)
			}
			result = append(result, value[:end])
			value = value[end:]
		}
	}
	return result, nil
}

func canonicalModuleFields(list *ast.FieldList, aliases map[string]string, pkg string) string {
	var values []string
	if list != nil {
		for _, f := range list.List {
			n := len(f.Names)
			if n == 0 {
				n = 1
			}
			for range n {
				values = append(values, canonicalModuleType(f.Type, aliases, pkg))
			}
		}
	}
	return strings.Join(values, ",")
}
func canonicalModuleType(expr ast.Expr, aliases map[string]string, pkg string) string {
	switch e := expr.(type) {
	case *ast.Ident:
		if e.Name == "error" || e.Name == "string" || e.Name == "bool" || e.Name == "int64" || e.Name == "float64" || e.Name == "float32" {
			return e.Name
		}
		return pkg + "." + e.Name
	case *ast.SelectorExpr:
		if id, ok := e.X.(*ast.Ident); ok {
			return aliases[id.Name] + "." + e.Sel.Name
		}
	case *ast.StarExpr:
		return "*" + canonicalModuleType(e.X, aliases, pkg)
	case *ast.IndexExpr:
		return canonicalModuleType(e.X, aliases, pkg) + "[" + canonicalModuleType(e.Index, aliases, pkg) + "]"
	case *ast.IndexListExpr:
		var types []string
		for _, t := range e.Indices {
			types = append(types, canonicalModuleType(t, aliases, pkg))
		}
		return canonicalModuleType(e.X, aliases, pkg) + "[" + strings.Join(types, ",") + "]"
	case *ast.ArrayType:
		if n, ok := e.Len.(*ast.BasicLit); ok {
			return "[" + n.Value + "]" + canonicalModuleType(e.Elt, aliases, pkg)
		}
	}
	return "<unsupported>"
}

func checkModuleBehavior(b moduleBehavior) error {
	context := "*" + moduleAPI + ".Context"
	expected := map[string]string{
		"Install": context, "Destroy": context, "Exit": context, "Suspend": context,
		"Enter": context + "," + moduleAPI + ".SceneStartup", "Resume": context + "," + moduleAPI + ".SceneStartup",
		"Update": context + "," + moduleAPI + ".Tick", "OnMessage": context + "," + moduleAPI + ".Message",
		"FrameUpdate": context + "," + moduleAPI + ".Tick",
	}
	for _, name := range sortedWorkspaceKeys(expected) {
		method, ok := b.pkg.methods[b.typeName][name]
		want := expected[name] + " -> error"
		if !ok {
			continue
		}
		if method.signature != want {
			return fmt.Errorf("%s: %s.%s signature %s; expected %s (declared by %s)", method.file, b.typeName, name, method.signature, want, b.file)
		}
		if !method.pointer {
			return fmt.Errorf("%s: behavior %s.%s must use a pointer receiver", method.file, b.typeName, name)
		}
	}
	return nil
}

func moduleGoType(t project.ValueType, schemas map[project.ValueType]project.ValueSchema) string {
	switch t {
	case "":
		return "module.Signal"
	case project.StringValue:
		return "string"
	case project.BoolValue:
		return "bool"
	case project.IntValue:
		return "int64"
	case project.NumberValue:
		return "float64"
	case project.Vec2Value:
		return "[2]float32"
	case project.Vec3Value:
		return "[3]float32"
	case project.ColorValue:
		return "[4]float32"
	case project.VisualValue:
		return "module.RenderOutputHandle"
	case "TextRenderRequest", "TextRenderResult", "SceneSwitchRequest", "SceneSwitchResult", "SceneStartup", "Collision2D", "Collision3D":
		return "module." + string(t)
	}
	if _, ok := schemas[t]; ok {
		return "contracts." + string(t)
	}
	return ""
}

func generateModuleContracts(schemas map[project.ValueType]project.ValueSchema) ([]byte, error) {
	var body strings.Builder
	needsModule := false
	for _, name := range sortedWorkspaceKeys(schemas) {
		fmt.Fprintf(&body, "type %s struct {\n", name)
		fields := sortedWorkspaceKeys(schemas[name].Fields)
		goNames := make(map[string]bool, len(fields))
		for _, field := range fields {
			goName := moduleContractField(field)
			if !token.IsIdentifier(goName) || !ast.IsExported(goName) || goNames[goName] {
				return nil, fmt.Errorf("types.%s.fields.%s: generated Go field is invalid or duplicated", name, field)
			}
			goNames[goName] = true
			t := moduleGoType(schemas[name].Fields[field], schemas)
			if t == "" {
				return nil, fmt.Errorf("types.%s.fields.%s: unknown protocol", name, field)
			}
			needsModule = needsModule || strings.HasPrefix(t, "module.")
			fmt.Fprintf(&body, "%s %s `json:%s`\n", goName, strings.TrimPrefix(t, "contracts."), strconv.Quote(field))
		}
		fmt.Fprintf(&body, "}\n\nfunc Decode%s(v project.SlotValue) (%s,error) {\nvar out %s\nif v.Type != %q || len(v.Fields) != %d { return out, fmt.Errorf(\"invalid %s value\") }\n", name, name, name, name, len(fields), name)
		for i, field := range fields {
			t := schemas[name].Fields[field]
			fmt.Fprintf(&body, "if v.Fields[%d].Name != %q || v.Fields[%d].Value.Type != %q { return out, fmt.Errorf(\"invalid %s.%s value\") }\n", i, field, i, t, name, field)
			expr := ""
			switch t {
			case project.StringValue:
				expr = "String"
			case project.BoolValue:
				expr = "Bool"
			case project.NumberValue:
				expr = "Number"
			case project.IntValue:
				expr = "Integer"
			}
			goField := moduleContractField(field)
			if expr != "" {
				fmt.Fprintf(&body, "out.%s = v.Fields[%d].Value.%s\n", goField, i, expr)
			} else if t == project.Vec2Value || t == project.Vec3Value || t == project.ColorValue {
				n := 4
				if t == project.Vec2Value {
					n = 2
				}
				if t == project.Vec3Value {
					n = 3
				}
				fmt.Fprintf(&body, "copy(out.%s[:],v.Fields[%d].Value.Vector[:%d])\n", goField, i, n)
			} else if _, ok := schemas[t]; ok {
				fmt.Fprintf(&body, "{ value, err := Decode%s(v.Fields[%d].Value); if err != nil { return out,err }; out.%s = value }\n", t, i, goField)
			} else {
				return nil, fmt.Errorf("types.%s.fields.%s: %s is not an authored data value", name, field, t)
			}
		}
		body.WriteString("return out,nil\n}\n\n")
	}
	source := moduleGeneratedHeader + "package contracts\nimport (\n\"fmt\"\n\"github.com/diiyw/onix/project\"\n"
	if needsModule {
		source += "\"" + moduleAPI + "\"\n"
	}
	source += ")\n" + body.String()
	if len(schemas) == 0 {
		return nil, nil
	}
	return format.Source([]byte(source))
}
func moduleContractField(name string) string {
	var out strings.Builder
	upper := true
	for _, r := range name {
		if r == '_' || r == '-' {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		out.WriteRune(r)
	}
	return out.String()
}

// CreateModuleProject supplies the local engine dependency for independent
// projects. Projects inside an existing Go module keep that module unchanged.
func CreateModuleProject(directory string, options project.CreateProjectOptions) (*project.ProjectPlan, error) {
	if options.EngineDirectory == "" && options.EngineVersion == "" {
		_, file, _, ok := runtime.Caller(0)
		if ok {
			root, err := findRepoRoot(filepath.Dir(file))
			if name, _ := modulePath(root); err == nil && name == "github.com/diiyw/onix" {
				options.EngineDirectory = root
			}
		}
		if options.EngineDirectory == "" {
			return nil, fmt.Errorf("cannot locate local engine; specify an engine directory or version")
		}
	}
	return project.CreateProjectDirectory(directory, options)
}
