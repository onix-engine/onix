package project

import (
	"fmt"
	"io/fs"
	"strings"
)

// ShaderSpec maps one named shader resource to the native source files used
// by Onix's render backends. Missing stages inherit the built-in pipeline stage.
type ShaderSpec struct {
	ID string `json:"id"`
	ShaderSources
}

// ShaderSources holds the source paths used by shader compilation and loading.
type ShaderSources struct {
	WGSLVertex      string `json:"wgslVertex,omitempty"`
	WGSLFragment    string `json:"wgslFragment,omitempty"`
	VulkanVertex    string `json:"vulkanVertex,omitempty"`
	VulkanFragment  string `json:"vulkanFragment,omitempty"`
	Metal           string `json:"metal,omitempty"`
	WebGL2Vertex    string `json:"webGL2Vertex,omitempty"`
	WebGL2Fragment  string `json:"webGL2Fragment,omitempty"`
	WebGPUVertex    string `json:"webGPUVertex,omitempty"`
	WebGPUFragment  string `json:"webGPUFragment,omitempty"`
	WebGL2Generated bool   `json:"webGL2Generated,omitempty"`
}

// ShaderComponentSpec authors WGSL stages and per-element uniforms.
// Compiled is generated by the build tools and retained only in binary plans.
type ShaderComponentSpec struct {
	WGSLVertex   string        `json:"wgslVertex,omitempty"`
	WGSLFragment string        `json:"wgslFragment,omitempty"`
	Custom       [4][4]float32 `json:"custom,omitzero"`
	Compiled     ShaderSources `json:"-"`
}

func (s ShaderComponentSpec) SourcePaths() [2]string {
	return [2]string{s.WGSLVertex, s.WGSLFragment}
}

func (s ShaderComponentSpec) wgslSources() ShaderSources {
	return ShaderSources{WGSLVertex: s.WGSLVertex, WGSLFragment: s.WGSLFragment}
}

func (s ShaderComponentSpec) HasSource() bool {
	return s.wgslSources().HasSource() || s.Compiled.HasSource()
}

type ShaderTarget uint8

const (
	ShaderTargetAll ShaderTarget = iota
	ShaderTargetVulkan
	ShaderTargetMetal
	ShaderTargetWebGL2
	ShaderTargetWebGPU
	ShaderTargetAndroid
)

func (target ShaderTarget) valid() bool {
	return target <= ShaderTargetAndroid
}

func (target ShaderTarget) String() string {
	switch target {
	case ShaderTargetAll:
		return "all"
	case ShaderTargetVulkan:
		return "Vulkan"
	case ShaderTargetMetal:
		return "Metal"
	case ShaderTargetWebGL2:
		return "WebGL2"
	case ShaderTargetWebGPU:
		return "WebGPU"
	case ShaderTargetAndroid:
		return "Android"
	default:
		return fmt.Sprintf("ShaderTarget(%d)", target)
	}
}

func (s ShaderSpec) forTarget(target ShaderTarget) (ShaderSpec, error) {
	result := s
	result.WGSLVertex = strings.TrimSpace(result.WGSLVertex)
	result.WGSLFragment = strings.TrimSpace(result.WGSLFragment)
	result.VulkanVertex = strings.TrimSpace(result.VulkanVertex)
	result.VulkanFragment = strings.TrimSpace(result.VulkanFragment)
	result.Metal = strings.TrimSpace(result.Metal)
	result.WebGL2Vertex = strings.TrimSpace(result.WebGL2Vertex)
	result.WebGL2Fragment = strings.TrimSpace(result.WebGL2Fragment)
	result.WebGPUVertex = strings.TrimSpace(result.WebGPUVertex)
	result.WebGPUFragment = strings.TrimSpace(result.WebGPUFragment)
	if err := result.Validate(); err != nil {
		return ShaderSpec{}, err
	}
	switch target {
	case ShaderTargetAll:
		return result, nil
	case ShaderTargetVulkan:
		result.WGSLVertex, result.WGSLFragment, result.Metal, result.WebGL2Vertex, result.WebGL2Fragment, result.WebGPUVertex, result.WebGPUFragment = "", "", "", "", "", "", ""
		if result.VulkanVertex == "" && result.VulkanFragment == "" {
			return ShaderSpec{}, fmt.Errorf("shader %q has no Vulkan source", strings.TrimSpace(s.ID))
		}
	case ShaderTargetMetal:
		result.WGSLVertex, result.WGSLFragment, result.VulkanVertex, result.VulkanFragment, result.WebGL2Vertex, result.WebGL2Fragment, result.WebGPUVertex, result.WebGPUFragment = "", "", "", "", "", "", "", ""
		if result.Metal == "" {
			return ShaderSpec{}, fmt.Errorf("shader %q has no Metal source", strings.TrimSpace(s.ID))
		}
	case ShaderTargetWebGL2:
		result.WGSLVertex, result.WGSLFragment, result.VulkanVertex, result.VulkanFragment, result.Metal, result.WebGPUVertex, result.WebGPUFragment = "", "", "", "", "", "", ""
		if result.WebGL2Vertex == "" && result.WebGL2Fragment == "" {
			return ShaderSpec{}, fmt.Errorf("shader %q has no WebGL2 source", strings.TrimSpace(s.ID))
		}
	case ShaderTargetWebGPU:
		result.VulkanVertex, result.VulkanFragment, result.Metal, result.WebGL2Vertex, result.WebGL2Fragment = "", "", "", "", ""
		if result.WebGPUVertex == "" && result.WebGPUFragment == "" {
			return ShaderSpec{}, fmt.Errorf("shader %q has no WebGPU source", strings.TrimSpace(s.ID))
		}
	case ShaderTargetAndroid:
		result.WGSLVertex, result.WGSLFragment, result.Metal, result.WebGPUVertex, result.WebGPUFragment = "", "", "", "", ""
		if result.VulkanVertex == "" && result.VulkanFragment == "" {
			return ShaderSpec{}, fmt.Errorf("shader %q has no Vulkan source for Android", strings.TrimSpace(s.ID))
		}
		if result.WebGL2Vertex == "" && result.WebGL2Fragment == "" {
			return ShaderSpec{}, fmt.Errorf("shader %q has no GLSL ES source for Android", strings.TrimSpace(s.ID))
		}
	default:
		return ShaderSpec{}, fmt.Errorf("unsupported shader target %d", target)
	}
	return result, nil
}

func (s ShaderSources) SourcePaths() [9]string {
	return [...]string{s.WGSLVertex, s.WGSLFragment, s.VulkanVertex, s.VulkanFragment, s.Metal, s.WebGL2Vertex, s.WebGL2Fragment, s.WebGPUVertex, s.WebGPUFragment}
}

func (s ShaderSpec) Validate() error {
	id := strings.TrimSpace(s.ID)
	if id == "" {
		return fmt.Errorf("shader id is required")
	}
	if err := s.ShaderSources.Validate(); err != nil {
		return fmt.Errorf("shader %q: %w", id, err)
	}
	return nil
}

func (s ShaderSources) Validate() error {
	if !s.HasSource() {
		return fmt.Errorf("shader requires at least one platform source")
	}
	for _, path := range s.SourcePaths() {
		if strings.TrimSpace(path) == "" {
			continue
		}
		if _, err := NormalizeResourcePath(path); err != nil {
			return fmt.Errorf("shader source: %w", err)
		}
	}
	return nil
}

func (s ShaderSources) HasSource() bool {
	for _, path := range s.SourcePaths() {
		if strings.TrimSpace(path) != "" {
			return true
		}
	}
	return false
}

func (s ShaderSpec) load(source fs.FS, baseDir string) (result shaderResource, resultErr error) {
	if err := s.Validate(); err != nil {
		return shaderResource{}, err
	}
	defer func() {
		if resultErr != nil {
			_ = result.dispose()
		}
	}()
	descriptor := &result.descriptor
	if s.WGSLVertex != "" || s.WGSLFragment != "" {
		return result, fmt.Errorf("shader %q contains uncompiled WGSL; run the editor resource build first", s.ID)
	}
	descriptor.WebGL2Generated = s.WebGL2Generated
	load := func(path string) ([]byte, error) {
		if strings.TrimSpace(path) == "" {
			return nil, nil
		}
		resolved, err := ResolveResourcePath(baseDir, path)
		if err != nil {
			return nil, fmt.Errorf("resolve %s: %w", path, err)
		}
		blob, err := openProjectBlob(source, resolved)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		data, err := blob.Bytes()
		if err != nil {
			_ = blob.Close()
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		result.sources = append(result.sources, blob)
		return data, nil
	}
	var err error
	if descriptor.VulkanVertexSPIRV, err = load(s.VulkanVertex); err != nil {
		return result, err
	}
	if descriptor.VulkanFragmentSPIRV, err = load(s.VulkanFragment); err != nil {
		return result, err
	}
	if source, loadErr := load(s.Metal); loadErr != nil {
		return result, loadErr
	} else {
		descriptor.MetalSource = string(source)
	}
	if source, loadErr := load(s.WebGL2Vertex); loadErr != nil {
		return result, loadErr
	} else {
		descriptor.WebGL2VertexSource = string(source)
	}
	if source, loadErr := load(s.WebGL2Fragment); loadErr != nil {
		return result, loadErr
	} else {
		descriptor.WebGL2FragmentSource = string(source)
	}
	if source, loadErr := load(s.WebGPUVertex); loadErr != nil {
		return result, loadErr
	} else {
		descriptor.WebGPUVertexSource = string(source)
	}
	if source, loadErr := load(s.WebGPUFragment); loadErr != nil {
		return result, loadErr
	} else {
		descriptor.WebGPUFragmentSource = string(source)
	}
	if err := descriptor.Validate(); err != nil {
		return result, fmt.Errorf("shader %q: %w", s.ID, err)
	}
	return result, nil
}
