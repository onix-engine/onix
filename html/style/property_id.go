type cascadedValues struct {
	entries []cascadedValue
	indices [propertyCount]uint8
}

func (v *cascadedValues) reset() {
	for _, entry := range v.entries {
		v.indices[entry.order.id] = 0
	}
	clear(v.entries)
	v.entries = v.entries[:0]
}

func (v *cascadedValues) get(id propertyID) (cascadedValue, bool) {
	if position := v.indices[id]; position != 0 {
		return v.entries[position-1], true
	}
	return cascadedValue{}, false
}
